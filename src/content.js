const ARABIC_DIGITS = '٠١٢٣٤٥٦٧٨٩';

/** 3 → '٣', 10 → '١٠' */
export function toArabicDigits(n) {
  return String(n).replace(/[0-9]/g, (d) => ARABIC_DIGITS[d]);
}

/** visitedText(3, 10) → 'زرت ٣ من ١٠ محطات' */
export function visitedText(visited, total) {
  return `زرت ${toArabicDigits(visited)} من ${toArabicDigits(total)} محطات`;
}
